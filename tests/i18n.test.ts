import { describe, expect, it } from 'vitest';
import { convert } from '../src/converter';
import { dialectLabel, text, translateConversionText } from '../src/i18n';

describe('interface translations', () => {
  it('uses English by default and provides French copy', () => {
    expect(text('pageTitle', 'en')).toBe('GLSL to Godot');
    expect(text('pageTitle', 'fr')).toBe('GLSL vers Godot');
    expect(dialectLabel('generic', 'en')).toBe('Generic GLSL (WebGL / OpenGL)');
    expect(dialectLabel('generic', 'fr')).toBe('GLSL générique (WebGL / OpenGL)');
  });

  it('translates conversion messages while preserving dynamic values', () => {
    const french = 'Fonction « noise » inconnue : elle n’est pas définie.';
    expect(translateConversionText('Colle un shader pour commencer.', 'en')).toBe('Paste a shader to get started.');
    expect(translateConversionText('La fonction « noise » est récursive : Godot interdit la récursion. Il faut la réécrire avec une boucle.', 'en'))
      .toBe('Function “noise” is recursive: Godot does not allow recursion. Rewrite it as a loop.');
    expect(translateConversionText(french, 'fr')).toBe(french);
  });

  it('localizes comments in generated shader and script files', () => {
    const fragment = 'void mainImage(out vec4 c, in vec2 f){ c = vec4(f / iResolution.xy, 0.0, 1.0); }';
    const english = convert({ fragment, language: 'en' });
    const french = convert({ fragment, language: 'fr' });
    expect(english.shader).toContain('// Converted from Shadertoy');
    expect(english.script).toContain('## Script generated by glsl2godot.');
    expect(french.shader).toContain('// Converti depuis Shadertoy');
    expect(french.script).toContain('## Script généré par glsl2godot.');
  });
});
